/**
 * CORE i18n ENGINE
 */

function getLang() {
  const savedLang = localStorage.getItem('stitch_lang');
  if (savedLang) return savedLang;
  
  const browserLang = navigator.language || navigator.userLanguage;
  if (browserLang) {
    if (browserLang.startsWith('ar')) return 'ar';
    if (browserLang.startsWith('fr')) return 'fr';
  }
  return 'en';
}

function applyLang(lang) {
  document.documentElement.lang = lang;
  localStorage.setItem('stitch_lang', lang);

  // RTL Support
  if (lang === 'ar') {
    document.documentElement.dir = 'rtl';
    document.body.classList.add('rtl');
  } else {
    document.documentElement.dir = 'ltr';
    document.body.classList.remove('rtl');
  }

  // Update static text
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key && translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key && translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Update Toggle UI (if it exists)
  const toggle = document.getElementById('language-toggle');
  const label = document.getElementById('current-language');
  if (toggle) {
    toggle.classList.remove('lang-en', 'lang-fr', 'lang-ar');
    toggle.classList.add(`lang-${lang}`);
    if (label) {
      label.textContent = lang === 'en' ? 'English' : (lang === 'fr' ? 'Français' : 'العربية');
    }
  }

  // Notify page scripts to re-render dynamic content
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  
  // Also call local render functions if they exist (backward compatibility)
  if (typeof renderProducts === 'function') renderProducts();
  if (typeof renderCategories === 'function') renderCategories();
}

function getTranslation(key) {
  const lang = getLang();
  return (translations[lang] && translations[lang][key]) || (translations['en'] && translations['en'][key]) || key;
}

function getMenuTranslation(item, field) {
  const lang = getLang();
  if (lang === 'en') return item[field];
  
  // Use unique ID if available, otherwise fallback to name-based lookup
  const key = item.id || item.name;
  if (menuTranslations[key] && menuTranslations[key][lang] && menuTranslations[key][lang][field]) {
    return menuTranslations[key][lang][field];
  }
  
  // Fallback to name-based lookup if ID didn't work
  if (menuTranslations[item.name] && menuTranslations[item.name][lang] && menuTranslations[item.name][lang][field]) {
    return menuTranslations[item.name][lang][field];
  }

  return item[field];
}

// Auto-run on load
document.addEventListener('DOMContentLoaded', () => {
  const lang = getLang();
  applyLang(lang);
  
  // Global listener for language toggles across all pages
  const toggle = document.getElementById('language-toggle');
  if (toggle) {
    toggle.addEventListener('click', function () {
      const current = getLang();
      let next = 'en';
      if (current === 'en') next = 'fr';
      else if (current === 'fr') next = 'ar';
      else if (current === 'ar') next = 'en';
      applyLang(next);
    });
  }
});
