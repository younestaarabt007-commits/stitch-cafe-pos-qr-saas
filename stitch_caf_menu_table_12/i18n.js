function getMenuTranslation(item, field) {
  if (!item) return '';
  const lang = getLang();
  if (lang === 'ar') {
    if (field === 'name') return getLocalizedItemName(item);
    if (field === 'description') return getLocalizedItemDesc(item);
  }
  return item[field] || '';
}

function getTranslation(key) {
  const lang = getLang();
  return (translations[lang] && translations[lang][key]) || (translations['fr'] && translations['fr'][key]) || (translations['en'] && translations['en'][key]) || key;
}

function getLang() {
  try {
    if (typeof window !== 'undefined' && window.location && window.location.search) {
      const urlParams = new URLSearchParams(window.location.search);
      const urlLang = urlParams.get('lang');
      if (urlLang && ['fr', 'ar', 'en'].includes(urlLang.toLowerCase())) {
        const clean = urlLang.toLowerCase();
        try { localStorage.setItem('stitch_lang', clean); } catch (_) {}
        return clean;
      }
    }
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('stitch_lang');
      if (saved && ['fr', 'ar', 'en'].includes(saved)) return saved;
    }
  } catch (_) {}

  try {
    if (typeof navigator !== 'undefined') {
      const browserLang = navigator.language || navigator.userLanguage;
      if (browserLang) {
        if (browserLang.startsWith('ar')) return 'ar';
        if (browserLang.startsWith('fr')) return 'fr';
      }
    }
  } catch (_) {}
  return 'fr';
}

function applyLang(lang) {
  if (!['fr', 'ar', 'en'].includes(lang)) lang = 'fr';
  try {
    localStorage.setItem('stitch_lang', lang);
  } catch (_) {}

  const isRtl = lang === 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = isRtl ? 'rtl' : 'ltr';

  if (document.body) {
    if (isRtl) {
      document.body.classList.add('rtl');
    } else {
      document.body.classList.remove('rtl');
    }
  }

  // Update static text elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key && translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update inner HTML elements
  document.querySelectorAll('[data-i18n-inner]').forEach(el => {
    const key = el.getAttribute('data-i18n-inner');
    if (key && translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key && translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Notify scripts across page
  try {
    document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  } catch (_) {}

  // Trigger page re-renderers if present
  if (typeof renderBestsellers === 'function' && typeof bestsellers !== 'undefined') {
    try { renderBestsellers(bestsellers); } catch (_) {}
  }
  if (typeof renderCategories === 'function') {
    try { renderCategories(); } catch (_) {}
  }
  if (typeof checkAndRenderTableConflictBanner === 'function') {
    try { checkAndRenderTableConflictBanner(); } catch (_) {}
  }
  if (typeof renderStitchCartModalItems === 'function') {
    try { renderStitchCartModalItems(); } catch (_) {}
  }
}

